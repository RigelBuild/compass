// The compass.v1 agent->Runner call transport (design
// docs/designs/product/compass-agent-runner-transport/design.md, SEA-1351 T1).
//
// INTERNAL-ONLY surface. Unlike compass.proto / comms.proto — the public,
// generated-client door between a UI and the Server — AgentGateway is the
// Runner-side LISTENER for calls the in-container first-party agent makes to its
// Runner. It runs the OPPOSITE direction to RunnerService (runner.proto, which
// is Runner->Server dial-out): here the agent is the client and the Runner is
// the server, over a per-container bind-mounted Unix socket (a local hop, no
// network path — the egress seal is untouched). It is generated ONLY into the
// internal lanes (the Runner's Go handler via buf.gen.internal-go.yaml; the
// agent's TS client via buf.gen.agent-ts.yaml), never onto the public client
// surface, so the `@compass/client` server-door fence stays intact (the agent is
// not a server-door client). The gen fan-out that enforces this is a separate
// path-filtered lane; the public buf.gen.yaml excludes this file.
//
// Additive and buf-breaking-safe: a new file in the owned `compass.v1` package,
// not a change to the public messages. `buf lint`/`buf breaking` still cover it
// (they glob `compass/**/*.proto`).
//
// Naming: the service is a `Gateway` (a Runner-side door for agent calls), not a
// public `*Service`, and its sole RPC `Comms` carries the general
// `CommsCallRequest`/`CommsCallResult` envelopes — named for the call family,
// NOT `CommsRequest`/`CommsResponse`, because the SAME messages are reused
// verbatim as the `RelayCommsCallRequest.call` / `RelayCommsCallResponse.result`
// payloads on the Runner->Server leg (runner.proto RelayCommsCall). Sharing one
// envelope across both hops is the point; renaming per-RPC would fork the wire.
// buf's SERVICE_SUFFIX / RPC_REQUEST_STANDARD_NAME / RPC_RESPONSE_STANDARD_NAME
// are ignore_only-scoped to this file in buf.yaml for exactly that reason.

